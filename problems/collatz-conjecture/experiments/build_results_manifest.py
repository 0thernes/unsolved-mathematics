#!/usr/bin/env python3
"""
build_results_manifest.py — machine-readable provenance for experiments/results/.

Indexes every result JSON with its size, top-level keys (a content fingerprint),
and a best-guess producer script, so the 190+ result files stop being an opaque
blob. Run from experiments/ (or anywhere); writes results/MANIFEST.json.
"""
from __future__ import annotations
import os, json

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")

def guess_producer(stem: str) -> str | None:
    # strip common result suffixes, then look for a matching instrument
    cands = {stem, stem + "_check", stem + "_scan", stem + "_analyzer",
             stem + "_probe", stem.replace("_scan", ""), stem.replace("_check", "")}
    # also strip trailing _<digits> or _<date>
    base = stem
    for sep in ("_20", "_d", "_"):
        if sep in base:
            base = base.rsplit(sep, 1)[0]
            cands.add(base)
            for suf in ("", "_check", "_scan", "_analyzer", "_probe", "_lab"):
                cands.add(base + suf)
    for c in cands:
        p = os.path.join(HERE, c + ".py")
        if os.path.isfile(p):
            return c + ".py"
    return None

def main() -> int:
    entries = []
    total = 0
    names = sorted(f.name for f in os.scandir(RESULTS)
                   if f.is_file() and f.name.endswith(".json")) if os.path.isdir(RESULTS) else []
    for name in names:
        path = os.path.join(RESULTS, name)
        if name == "MANIFEST.json":
            continue
        size = os.path.getsize(path); total += size
        keys = None
        try:
            with open(path, encoding="utf-8") as f:
                obj = json.load(f)
            if isinstance(obj, dict):
                keys = list(obj.keys())[:8]
        except Exception:
            keys = ["<unparseable>"]
        entries.append({
            "file": name,
            "size_bytes": size,
            "top_keys": keys,
            "producer": guess_producer(os.path.splitext(name)[0]),
        })
    manifest = {
        "note": "Auto-generated by build_results_manifest.py. Do not edit by hand.",
        "count": len(entries),
        "total_bytes": total,
        "orphans_no_producer": sum(1 for e in entries if e["producer"] is None),
        "results": entries,
    }
    out = os.path.join(RESULTS, "MANIFEST.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    print(f"MANIFEST.json: {len(entries)} result sets, {total/1024:.0f} KB, "
          f"{manifest['orphans_no_producer']} with no matched producer.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

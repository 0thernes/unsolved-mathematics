def render_all(
    snap: dict[str, Any], items: dict[str, list[dict[str, Any]]], crosswalk: dict[str, Any]
) -> dict[Path, str]:
    out: dict[Path, str] = {
        DOC_PROGRAMS: render_programs_md(snap, crosswalk),
        DOC_CROSSWALK: render_crosswalk_md(snap, crosswalk),
        CROSSWALK: json.dumps(crosswalk, ensure_ascii=False, indent=2) + "\n",
    }
    for prog in snap["programs"]:
        if prog.get("mirrored"):
            out[DOC_PROGRAM_DIR / f"{prog['slug']}.md"] = render_program_md(prog, items[prog["slug"]], snap)
    return out



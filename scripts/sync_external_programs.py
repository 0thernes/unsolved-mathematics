def diff_summary(old: tuple[dict[str, Any], dict[str, list[dict[str, Any]]]] | None,
                 new_snap: dict[str, Any], new_items: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    entry: dict[str, Any] = {"date_utc": new_snap["last_changed_utc"], "content_sha256": new_snap["content_sha256"]}
    if old is None:
        entry["event"] = "initial-snapshot"
        entry["mirrored_items"] = new_snap["totals"]["mirrored_items"]
        return entry
    old_snap, old_items = old
    old_p = {p["name"]: p for p in old_snap["programs"]}
    deltas: dict[str, dict[str, int]] = {}
    for p in new_snap["programs"]:
        o = old_p.get(p["name"])
        for key in ("targets", "open", "solved_here"):
            d = p[key] - (o[key] if o else 0)
            if d:
                deltas.setdefault(p["name"], {})[key] = d
    old_by = {it["id"]: it for rows in old_items.values() for it in rows}
    new_by = {it["id"]: it for rows in new_items.values() for it in rows}
    flips = []
    for iid in sorted(set(old_by) & set(new_by)):
        for f in ("kind", "solved"):
            if old_by[iid][f] != new_by[iid][f]:
                flips.append({"id": iid, "field": f, "old": old_by[iid][f], "new": new_by[iid][f]})
    entry.update(
        {
            "event": "update",
            "program_deltas": deltas,
            "items_added": len(set(new_by) - set(old_by)),
            "items_removed": len(set(old_by) - set(new_by)),
            "flips": flips[:500],
            "flips_total": len(flips),
        }
    )
    return entry


def cmd_sync(allow_shrink: bool) -> int:
    snap, items = fetch_live()
    old = load_snapshot() if SNAPSHOT.exists() else None
    snap["content_sha256"] = content_hash(snap, items)
    if old is not None:
        if old[0].get("content_sha256") == snap["content_sha256"]:
            print(f"Unchanged since {old[0].get('last_changed_utc')} (content {snap['content_sha256'][:16]}); nothing written.")
            return 0
        prev = old[0]["totals"]["mirrored_items"]
        if not allow_shrink and prev and snap["totals"]["mirrored_items"] < SHRINK_GUARD * prev:
            raise RuntimeError(
                f"Mirrored items fell from {prev} to {snap['totals']['mirrored_items']} (>20%); refusing to write. "
                "Re-run with --allow-shrink after manual review."
            )
    snap["last_changed_utc"] = datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    ordered = {k: snap[k] for k in ("schema_version", "last_changed_utc", "content_sha256", "source", "upstream",
                                     "item_index_policy", "totals", "programs")}
    # Write: items, snapshot, history, derived views.
    if ITEMS_DIR.exists():
        for stale in ITEMS_DIR.glob("*.jsonl"):
            if stale.stem not in items:
                stale.unlink()
    for pslug, rows in items.items():
        write_text(ITEMS_DIR / f"{pslug}.jsonl", "".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in rows))
    write_text(SNAPSHOT, json.dumps(ordered, ensure_ascii=False, indent=2) + "\n")
    entry = diff_summary(old, ordered, items)
    with HISTORY.open("a", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(entry, ensure_ascii=False, sort_keys=True) + "\n")
    rendered = render_views(ordered, items)
    print(f"Wrote snapshot {snap['content_sha256'][:16]}: {len(ordered['programs'])} programs, "
          f"{ordered['totals']['mirrored_items']} mirrored items, {len(rendered)} derived files.")
    return 0


def render_views(snap: dict[str, Any], items: dict[str, list[dict[str, Any]]]) -> dict[Path, str]:
    crosswalk = build_crosswalk(snap, items, load_problems(), load_overrides())
    crosswalk["snapshot_content_sha256"] = snap["content_sha256"]
    rendered = render_all(snap, items, crosswalk)
    if DOC_PROGRAM_DIR.exists():
        keep = {p.name for p in rendered if p.parent == DOC_PROGRAM_DIR}
        for stale in DOC_PROGRAM_DIR.glob("*.md"):
            if stale.name not in keep:
                stale.unlink()
    for path, text in rendered.items():
        write_text(path, text)
    return rendered


def cmd_check() -> int:
    errors: list[str] = []
    if not SNAPSHOT.exists():
        print("ERROR: data/external/lefttosolve/snapshot.json missing; run a live sync first.", file=sys.stderr)
        return 1
    snap, items = load_snapshot()
    if snap.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"schema_version {snap.get('schema_version')} != {SCHEMA_VERSION}")
    recomputed = content_hash(snap, items)
    if recomputed != snap.get("content_sha256"):
        errors.append(f"content_sha256 mismatch: recorded {snap.get('content_sha256')} vs recomputed {recomputed}")
    slugs = [p["slug"] for p in snap["programs"]]
    if len(slugs) != len(set(slugs)):
        errors.append("duplicate program slugs")
    for p in snap["programs"]:
        if p.get("mirrored"):
            rows = items.get(p["slug"], [])
            if len(rows) != p["mirrored_count"]:
                errors.append(f"{p['name']}: {len(rows)} item rows vs mirrored_count {p['mirrored_count']}")
            ids = [r["id"] for r in rows]
            if ids != sorted(set(ids)):
                errors.append(f"{p['name']}: item ids not unique+sorted")
            for r in rows:
                if set(r) != set(ITEM_FIELDS):
                    errors.append(f"{p['name']}: item {r.get('id')} has fields {sorted(r)}")
                    break
        elif p["name"] not in COUNTS_ONLY_PROGRAMS:
            errors.append(f"{p['name']}: not mirrored but not in the counts-only policy list")
        if sum(p["kinds"].values()) != p["api_total"]:
            errors.append(f"{p['name']}: kind counts {p['kinds']} do not sum to api_total {p['api_total']}")
    stray = sorted(f.stem for f in ITEMS_DIR.glob("*.jsonl") if f.stem not in items)
    if stray:
        errors.append(f"stray item files: {stray}")
    crosswalk = build_crosswalk(snap, items, load_problems(), load_overrides())
    crosswalk["snapshot_content_sha256"] = snap["content_sha256"]
    for path, text in render_all(snap, items, crosswalk).items():
        if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            errors.append(f"stale generated view: {path.relative_to(ROOT).as_posix()} (run --render)")
    if DOC_PROGRAM_DIR.exists():
        expected = {f"{p['slug']}.md" for p in snap["programs"] if p.get("mirrored")}
        extra = sorted(f.name for f in DOC_PROGRAM_DIR.glob("*.md") if f.name not in expected)
        if extra:
            errors.append(f"stray program views: {extra}")
    if HISTORY.exists():
        for n, line in enumerate(HISTORY.read_text(encoding="utf-8").splitlines(), 1):
            try:
                json.loads(line)
            except json.JSONDecodeError:
                errors.append(f"history.jsonl line {n} is not valid JSON")
    if errors:
        print("EXTERNAL PROGRAMS CHECK FAILED:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1
    t = snap["totals"]
    print(
        f"OK: external program mirror verified offline — {t['programs']} programs, {t['sum_card_targets']:,} targets, "
        f"{t['mirrored_items']:,} mirrored items, crosswalk {crosswalk['summary']['problems_with_matches']}/"
        f"{crosswalk['summary']['atlas_problems']} (content {snap['content_sha256'][:16]}, last change {snap['last_changed_utc']})."
    )
    return 0


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    except Exception:
        pass
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="offline integrity + freshness-of-views check (no network)")
    g.add_argument("--render", action="store_true", help="offline re-render of views from the committed snapshot")
    ap.add_argument("--allow-shrink", action="store_true", help="permit >20%% drop in mirrored items (manual review)")
    args = ap.parse_args()
    if args.check:
        return cmd_check()
    if args.render:
        snap, items = load_snapshot()
        rendered = render_views(snap, items)
        print(f"Re-rendered {len(rendered)} views from snapshot {snap['content_sha256'][:16]}.")
        return 0
    return cmd_sync(args.allow_shrink)


if __name__ == "__main__":
    raise SystemExit(main())

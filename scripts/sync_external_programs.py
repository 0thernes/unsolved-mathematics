# ----------------------------------------------------------------------------- utilities


def slugify(name: str) -> str:
    folded = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")


def norm_title(s: str) -> str:
    s = re.sub(r"[\u2010-\u2015\u2212]", " ", s)  # hyphen/en/em dashes, minus -> space (before ASCII folding)
    folded = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii").lower()
    folded = re.sub(r"\([^)]*\)", " ", folded)
    folded = folded.replace("'s ", " ").replace("'", "").replace("&", " and ")
    folded = re.sub(r"[^a-z0-9]+", " ", folded).strip()
    folded = re.sub(r"^(the|a|an) ", "", folded)
    return re.sub(r"\s+", " ", folded)


def strip_generic(s: str) -> str:
    words = s.split()
    while words and words[-1] in GENERIC_TAIL:
        words.pop()
    return " ".join(words)


def canonical_json(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def md_cell(s: object) -> str:
    return str(s).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").strip()


def fmt_int(n: int) -> str:
    return f"{n:,}"


# ----------------------------------------------------------------------------- parsing (pure)


def parse_programs_html(page: str) -> list[dict[str, Any]]:
    """Parse the /programs page cards into ordered program records (pure, testable)."""
    programs: list[dict[str, Any]] = []
    for m in re.finditer(r'<a href="/programs/([^"]+)"[^>]*class="rec"[^>]*>(.*?)</a>', page, re.S):
        href_name = urllib.parse.unquote(html.unescape(m.group(1)))
        inner = re.sub(r"<!--.*?-->", "", m.group(2), flags=re.S)
        divs = [html.unescape(re.sub(r"<[^>]+>", "", d)).strip() for d in re.findall(r"<div[^>]*>(.*?)</div>", inner, re.S)]
        name = next((d for d in divs if d == href_name), href_name)
        description = ""
        for d in divs:
            if d and d != name and not re.search(r"\blive\b|\btargets\b", d) and d != "front":
                description = d
                break
        text = html.unescape(re.sub(r"<[^>]+>", " ", inner))
        text = re.sub(r"\s+", " ", text)
        nums = re.search(r"(\d+) targets · (\d+) open · (\d+) solved here", text)
        if not nums:
            continue
        programs.append(
            {
                "name": name,
                "slug": slugify(name),
                "url": f"{PROGRAMS_PAGE}/{urllib.parse.quote(name)}",
                "description": description,
                "targets": int(nums.group(1)),
                "open": int(nums.group(2)),
                "solved_here": int(nums.group(3)),
            }
        )
    return programs


def normalize_item(raw: dict[str, Any]) -> dict[str, Any]:
    """Drop volatile/licensed fields (excerpt, liveAgents, claimed, difficulty)."""
    return {
        "id": str(raw["id"]),
        "title": str(raw.get("title") or ""),
        "kind": str(raw.get("kind") or ""),
        "fields": sorted(str(f) for f in (raw.get("fields") or [])),
        "prize": raw.get("prize"),
        "solved": bool(raw.get("solved")),
    }


def content_hash(snapshot: dict[str, Any], items: dict[str, list[dict[str, Any]]]) -> str:
    payload = {
        "upstream": snapshot.get("upstream"),
        "programs": snapshot.get("programs"),
        "items": {k: items[k] for k in sorted(items)},
    }
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


# ----------------------------------------------------------------------------- network


def http_get(url: str, retries: int = 4, timeout: int = 60) -> str:
    last: Exception | None = None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json, text/html"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                body: bytes = r.read()
            time.sleep(REQUEST_DELAY_S)
            return body.decode("utf-8")
        except urllib.error.HTTPError as e:
            last = e
            if e.code not in (429, 500, 502, 503, 504):
                raise
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            last = e
        time.sleep(5 * (2**attempt))
    raise RuntimeError(f"GET failed after {retries} attempts: {url}: {last}")


def api_page(params: dict[str, Any]) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(http_get(f"{API}?{urllib.parse.urlencode(params)}"))
    return data


def crawl_source(name: str) -> list[dict[str, Any]]:
    for attempt in range(2):
        first = api_page({"source": name, "limit": PAGE_LIMIT, "offset": 0})
        total = int(first["total"])
        seen: dict[str, dict[str, Any]] = {}
        page = first
        offset = 0
        while True:
            for raw in page["items"]:
                seen[str(raw["id"])] = normalize_item(raw)
            offset += PAGE_LIMIT
            if offset >= total:
                break
            page = api_page({"source": name, "limit": PAGE_LIMIT, "offset": offset})
        if len(seen) == total:
            return sorted(seen.values(), key=lambda it: it["id"])
        print(f"  ! {name}: crawled {len(seen)} unique ids but total={total}; retry {attempt + 1}")
    raise RuntimeError(f"Inconsistent crawl for program {name!r}; refusing to write a partial snapshot.")


def kind_counts_remote(name: str, total: int) -> dict[str, int]:
    counts = {k: int(api_page({"source": name, "kind": k, "limit": 1})["total"]) for k in ("open", "known", "unformalized")}
    counts["other"] = max(0, total - sum(counts.values()))
    return counts


def fetch_live() -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]]]:
    print(f"Fetching {PROGRAMS_PAGE} ...")
    programs = parse_programs_html(http_get(PROGRAMS_PAGE))
    if len(programs) < MIN_PROGRAMS:
        raise RuntimeError(f"Only {len(programs)} program cards parsed (< {MIN_PROGRAMS}); page layout changed?")
    head = api_page({"limit": 1})
    grand_total = int(head["total"])
    if grand_total < MIN_TOTAL:
        raise RuntimeError(f"API total {grand_total} < {MIN_TOTAL}; refusing to write.")
    upstream = head.get("upstream") or {}
    items: dict[str, list[dict[str, Any]]] = {}
    for prog in programs:
        name = prog["name"]
        if name in COUNTS_ONLY_PROGRAMS:
            api_total = int(api_page({"source": name, "limit": 1})["total"])
            prog["kinds"] = kind_counts_remote(name, api_total)
            prog["mirrored"] = False
            prog["mirrored_count"] = 0
        else:
            rows = crawl_source(name)
            api_total = len(rows)
            kinds: dict[str, int] = {"open": 0, "known": 0, "unformalized": 0, "other": 0}
            for r in rows:
                kinds[r["kind"] if r["kind"] in kinds else "other"] += 1
            prog["kinds"] = kinds
            prog["mirrored"] = True
            prog["mirrored_count"] = len(rows)
            prog["solved_flag_count"] = sum(1 for r in rows if r["solved"])
            items[prog["slug"]] = rows
        prog["api_total"] = api_total
        print(f"  {name}: card targets={prog['targets']} api_total={api_total} mirrored={prog['mirrored']}")
    sum_targets = sum(p["targets"] for p in programs)
    sum_api = sum(p["api_total"] for p in programs)
    snapshot: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "source": {
            "site": SITE,
            "programs_page": PROGRAMS_PAGE,
            "api": API,
            "site_source_repo": SOURCE_REPO,
            "site_source_license": "none declared (aggregate counts and identifiers only are mirrored)",
        },
        "upstream": {"repo": upstream.get("repo"), "commit": upstream.get("commit")},
        "item_index_policy": {
            "mirrored_fields": list(ITEM_FIELDS),
            "dropped_fields": ["excerpt", "difficulty", "liveAgents", "claimed"],
            "counts_only_programs": sorted(COUNTS_ONLY_PROGRAMS),
            "reason": "titles in counts-only programs are CC BY-SA user content; excerpts may carry CC BY-SA text",
        },
        "programs": programs,
        "totals": {
            "programs": len(programs),
            "api_total": grand_total,
            "sum_card_targets": sum_targets,
            "sum_api_totals": sum_api,
            "mirrored_items": sum(len(v) for v in items.values()),
            "consistent": sum_targets == grand_total == sum_api,
        },
    }
    return snapshot, items


# ----------------------------------------------------------------------------- load / derive


def load_snapshot() -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]]]:
    snap: dict[str, Any] = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    items: dict[str, list[dict[str, Any]]] = {}
    for prog in snap["programs"]:
        if prog.get("mirrored"):
            path = ITEMS_DIR / f"{prog['slug']}.jsonl"
            items[prog["slug"]] = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return snap, items


def load_problems() -> list[dict[str, Any]]:
    reg = yaml.safe_load(PROBLEMS_YAML.read_text(encoding="utf-8"))
    problems: list[dict[str, Any]] = reg["problems"]
    return problems


def load_overrides() -> dict[str, Any]:
    if not OVERRIDES.exists():
        return {"include": {}, "exclude": {}}
    data = yaml.safe_load(OVERRIDES.read_text(encoding="utf-8")) or {}
    return {"include": data.get("include") or {}, "exclude": data.get("exclude") or {}}


def build_crosswalk(
    snap: dict[str, Any],
    items: dict[str, list[dict[str, Any]]],
    problems: list[dict[str, Any]],
    overrides: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic Atlas -> external-item crosswalk (normalized-title rule + curated overrides)."""
    prog_name = {p["slug"]: p["name"] for p in snap["programs"]}
    by_id: dict[str, tuple[str, dict[str, Any]]] = {}
    index: dict[str, list[tuple[str, dict[str, Any]]]] = {}
    for pslug in sorted(items):
        for it in items[pslug]:
            by_id[it["id"]] = (pslug, it)
            base = it["title"].split(" — ")[0].rstrip(".")
            keys = {norm_title(base)}
            keys.add(strip_generic(norm_title(base)))
            for k in keys:
                if k:
                    index.setdefault(k, []).append((pslug, it))
    slugs = {p["slug"] for p in problems}
    for section in ("include", "exclude"):
        unknown = sorted(set(overrides[section]) - slugs)
        if unknown:
            raise ValueError(f"crosswalk-overrides.yaml {section}: unknown Atlas slugs {unknown}")
    rows: list[dict[str, Any]] = []
    for prob in problems:
        slug = prob["slug"]
        pkeys = {norm_title(prob["title"]), strip_generic(norm_title(prob["title"]))} - {""}
        found: dict[str, dict[str, Any]] = {}
        for k in sorted(pkeys):
            for pslug, it in index.get(k, []):
                found.setdefault(it["id"], {"via": "normalized-title", "program_slug": pslug, "item": it})
        for entry in overrides["include"].get(slug) or []:
            iid = entry if isinstance(entry, str) else str(entry["id"])
            if iid not in by_id:
                raise ValueError(f"crosswalk-overrides.yaml include[{slug}]: id {iid!r} not in mirrored item index")
            relation = None if isinstance(entry, str) else entry.get("relation")
            if relation is not None and relation not in RELATIONS:
                raise ValueError(f"crosswalk-overrides.yaml include[{slug}][{iid}]: relation {relation!r} not in {sorted(RELATIONS)}")
            pslug, it = by_id[iid]
            found[iid] = {"via": "curated-override", "program_slug": pslug, "item": it, "relation": relation}
        for iid in overrides["exclude"].get(slug) or []:
            found.pop(iid, None)
        matches = []
        for iid in sorted(found):
            f = found[iid]
            it = f["item"]
            primary = (".variants." not in iid) and (" — " not in it["title"])
            matches.append(
                {
                    "id": iid,
                    "program": prog_name.get(f["program_slug"], f["program_slug"]),
                    "program_slug": f["program_slug"],
                    "title": it["title"],
                    "kind": it["kind"],
                    "site_solved_flag": it["solved"],
                    "relation": f.get("relation") or ("primary" if primary else "variant"),
                    "via": f["via"],
                }
            )
        signals: list[str] = []
        status = prob.get("status", "")
        for m in matches:
            if m["relation"] == "primary" and m["kind"] == "known" and status in ("open", "active-progress"):
                signals.append(f"{m['id']}: formal-conjectures lists the primary statement as `known` while the Atlas status is `{status}`")
            if m["relation"] == "primary" and m["kind"] == "open" and status == "recently-resolved":
                signals.append(f"{m['id']}: formal-conjectures still lists the primary statement as `open` while the Atlas status is `recently-resolved`")
            if m["site_solved_flag"] and m["kind"] == "open" and m["relation"] != "related":
                signals.append(f"{m['id']}: lefttosolve.com marks this still-`open` statement solved by its agents (unverified third-party claim)")
        rows.append({"slug": slug, "title": prob["title"], "atlas_status": status, "matches": matches, "signals": signals})
    return {
        "schema_version": SCHEMA_VERSION,
        "snapshot_content_sha256": snap.get("content_sha256"),
        "rule": (
            "An external item matches an Atlas problem when the NFKD-folded, lower-cased, punctuation-free item base title "
            "(text before ' — ') equals the Atlas title, optionally after stripping trailing generic words "
            "(conjecture/problem/hypothesis/theorem/question); data/external/crosswalk-overrides.yaml adds reviewed ids "
            "(optionally fixing their relation) or removes false positives. Default relation=primary iff the id has no "
            "'.variants.' segment and the title has no ' — ' suffix; 'related' links never raise status signals."
        ),
        "summary": {
            "atlas_problems": len(rows),
            "problems_with_matches": sum(1 for r in rows if r["matches"]),
            "problems_with_primary_match": sum(1 for r in rows if any(m["relation"] == "primary" for m in r["matches"])),
            "total_matches": sum(len(r["matches"]) for r in rows),
            "problems_with_signals": sum(1 for r in rows if r["signals"]),
        },
        "problems": rows,
    }



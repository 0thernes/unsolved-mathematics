#!/usr/bin/env python3
"""
generate.py — The Atlas build engine.

Single source of truth: data/problems.yaml (+ VERSION for semantic version).
This script:
  1. Loads and validates every problem against schema/problem.schema.json
  2. Computes the Composite Severity Score (CSS) and canonical ranking with
     deterministic (-css, slug) tie-breaking
  3. Emits data/problems.json (machine registry with computed fields)
  4. Emits RANKING.md (the full ranked table)
  5. Scaffolds problems/<slug>/ folders with dossier templates (idempotent;
     never overwrites human-written prose — only creates what is missing,
     always refreshes derived metadata.json and the generated rank header
     blockquote in problems/<slug>/README.md)
  6. Refreshes the auto-generated ranking block inside README.md

Run:  python scripts/generate.py          (build everything)
      python scripts/generate.py --check  (validate + verify zero drift)

Pure standard library except PyYAML + jsonschema (see requirements.txt).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
except Exception:
    pass

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required:  pip install -r requirements.txt")

ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = ROOT / "VERSION"
REGISTRY_YAML = ROOT / "data" / "problems.yaml"
REGISTRY_JSON = ROOT / "data" / "problems.json"
SCHEMA = ROOT / "schema" / "problem.schema.json"
RANKING_MD = ROOT / "RANKING.md"
README = ROOT / "README.md"
PROBLEMS_DIR = ROOT / "problems"

README_BEGIN = "<!-- BEGIN:RANKING (auto-generated by scripts/generate.py — do not edit) -->"
README_END = "<!-- END:RANKING -->"

CURRENT_YEAR = 2026  # deliberately frozen reference year for v0.3.0 reproducible age scoring

HEADER_LINE_RE = re.compile(r"^> \*\*Atlas Rank #\d+\*\*.*$", re.MULTILINE)


def read_version(fallback: str = "0.3.0") -> str:
    if VERSION_FILE.exists():
        return VERSION_FILE.read_text(encoding="utf-8").strip()
    return fallback


# --------------------------------------------------------------------------- #
#  Scoring
# --------------------------------------------------------------------------- #
def age_score(year_posed: int) -> float:
    """Older problems score higher. Saturates at 100 (~300 years old)."""
    age = CURRENT_YEAR - year_posed
    return max(0.0, min(100.0, age / 3.0))


def composite_severity(p: dict) -> float:
    """CSS — higher means 'harder + older + more central + less tractable'."""
    return round(
        0.40 * p["difficulty"]
        + 0.30 * p["centrality"]
        + 0.20 * age_score(p["year_posed"])
        + 0.10 * (100 - p["tractability"]),
        3,
    )


def rank_problems(problems: list[dict]) -> list[tuple[int, float, dict]]:
    """Deterministic total order: descending CSS, then ascending slug."""
    ordered = sorted(problems, key=lambda p: (-composite_severity(p), p["slug"]))
    return [(i + 1, composite_severity(p), p) for i, p in enumerate(ordered)]


# --------------------------------------------------------------------------- #
#  Validation
# --------------------------------------------------------------------------- #
def validate(problems: list[dict]) -> list[str]:
    errors: list[str] = []
    slugs: set[str] = set()
    try:
        import jsonschema

        schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        validator = jsonschema.Draft202012Validator(schema)
    except ImportError:
        return ["jsonschema is required for registry validation: pip install -r requirements.txt"]
    except Exception as exc:
        return [f"failed to load schema {SCHEMA}: {exc}"]

    for i, p in enumerate(problems):
        ctx = f"problem[{i}] ({p.get('slug', '?')})"
        for err in validator.iter_errors(p):
            errors.append(f"{ctx}: schema: {err.message}")
        slug = p.get("slug")
        if slug in slugs:
            errors.append(f"{ctx}: duplicate slug '{slug}'")
        if isinstance(slug, str):
            slugs.add(slug)
    return errors


# --------------------------------------------------------------------------- #
#  Templates & header sync
# --------------------------------------------------------------------------- #
def fmt_year(y: int) -> str:
    return f"{abs(y)} BCE" if y < 0 else f"{y} CE" if y < 1000 else str(y)


def dossier_header_line(p: dict, rank: int, css: float) -> str:
    return (
        f"> **Atlas Rank #{rank}** · CSS **{css}** · Field: *{p['field']}* · "
        f"Posed: **{fmt_year(p['year_posed'])}** · Status: `{p['status']}`"
        + ("  · 🏛️ **Millennium Prize Problem**" if p["millennium_prize"] else "")
    )


def dossier_templates(p: dict, rank: int, css: float) -> dict[str, str]:
    title = p["title"]
    folder = p["slug"]  # stable, slug-only folder name (rank lives in metadata)
    origin = ", ".join(p["originators"])
    head = f"# {title}\n\n{dossier_header_line(p, rank, css)}\n\n"
    return {
        "README.md": head
        + f"## Plain statement\n\n{p['statement_plain'].strip()}\n\n"
        + "## Dossier contents\n\n"
        + "| File | Contents |\n|------|----------|\n"
        + "| [`history.md`](history.md) | Origin, formulation, and timeline |\n"
        + "| [`originator.md`](originator.md) | Biography of the originator(s) |\n"
        + "| [`approaches.md`](approaches.md) | Major attack strategies and partial results |\n"
        + "| [`attempts.md`](attempts.md) | Notable attempts, near-misses, and false proofs |\n"
        + "| [`papers.md`](papers.md) | The 25 most important papers (old + new) |\n"
        + "| [`mathematicians.md`](mathematicians.md) | Top 10 contributors, past and present |\n"
        + "| [`status.md`](status.md) | Current frontier and what a proof would require |\n"
        + "| [`metadata.json`](metadata.json) | Machine-readable record |\n"
        + "| [`rag/`](rag/) | Chunked corpus for retrieval-augmented generation |\n\n"
        + f"*Originators: {origin}.*\n",
        "history.md": f"# History — {title}\n\n_Origin, formulation, and timeline._\n\n"
        "<!-- DOSSIER:history -->\n",
        "originator.md": f"# Originator(s) — {title}\n\n_Biography, background, and the ideas that led here._\n\n"
        "<!-- DOSSIER:originator -->\n",
        "approaches.md": f"# Approaches — {title}\n\n_Major strategies, partial results, and barriers._\n\n"
        "<!-- DOSSIER:approaches -->\n",
        "attempts.md": f"# Attempts — {title}\n\n_Notable attempts, near-misses, retracted proofs._\n\n"
        "<!-- DOSSIER:attempts -->\n",
        "papers.md": f"# Key Papers — {title}\n\n_The 25 most important papers. Each carries a verification flag._\n\n"
        "<!-- DOSSIER:papers -->\n",
        "mathematicians.md": f"# Top Mathematicians — {title}\n\n_Ten figures who shaped the problem, past and present._\n\n"
        "<!-- DOSSIER:mathematicians -->\n",
        "status.md": f"# Status & Frontier — {title}\n\n_Where the problem stands and what a resolution would require._\n\n"
        "<!-- DOSSIER:status -->\n",
        "metadata.json": json.dumps(
            {**p, "rank": rank, "css": css, "folder": folder}, indent=2, ensure_ascii=False
        )
        + "\n",
        "rag/.gitkeep": "",
    }


def refresh_dossier_readme_text(existing: str, p: dict, rank: int, css: float) -> str:
    """Keep the generated Atlas Rank / CSS / Status header line synced without
    touching any human-authored prose below it."""
    new_line = dossier_header_line(p, rank, css)
    if HEADER_LINE_RE.search(existing):
        return HEADER_LINE_RE.sub(lambda _: new_line, existing, count=1)
    return existing


# --------------------------------------------------------------------------- #
#  Emitters
# --------------------------------------------------------------------------- #
def ranking_table(ranked: list[tuple[int, float, dict]]) -> str:
    rows = [
        "| # | Problem | Field | Posed | CSS | Difficulty | Status | 🏛️ |",
        "|---|---------|-------|-------|-----|-----------|--------|----|",
    ]
    for rank, css, p in ranked:
        link = f"[{p['title']}](problems/{p['slug']}/README.md)"
        mp = "✅" if p["millennium_prize"] else ""
        rows.append(
            f"| {rank} | {link} | {p['field']} | {fmt_year(p['year_posed'])} "
            f"| {css} | {p['difficulty']} | `{p['status']}` | {mp} |"
        )
    return "\n".join(rows)


def render_registry_json(ranked: list[tuple[int, float, dict]], meta: dict) -> str:
    out_meta = {**meta, "version": read_version(str(meta.get("version", "0.3.0")))}
    return (
        json.dumps(
            {
                "meta": out_meta,
                "problems": [{**p, "rank": r, "css": c} for r, c, p in ranked],
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    )


def render_ranking_md(ranked: list[tuple[int, float, dict]], meta: dict) -> str:
    ver = read_version(str(meta.get("version", "0.3.0")))
    return (
        "# 🏔️ The Master Ranking\n\n"
        f"_Atlas v{ver} · {len(ranked)} problems · reference year {CURRENT_YEAR} · "
        "ranked hardest+oldest → most tractable by Composite Severity Score (CSS), tie-broken alphabetically by slug._\n\n"
        "See [docs/methodology/RANKING.md](docs/methodology/RANKING.md) for the formula.\n\n"
        + ranking_table(ranked)
        + "\n\n> CSS = 0.40·difficulty + 0.30·centrality + 0.20·age + 0.10·(100−tractability).\n"
    )


def render_patched_readme(existing: str, ranked: list[tuple[int, float, dict]]) -> str:
    block = README_BEGIN + "\n\n" + ranking_table(ranked) + "\n\n" + README_END
    if README_BEGIN in existing and README_END in existing:
        pre = existing.split(README_BEGIN)[0]
        post = existing.split(README_END)[1]
        return pre + block + post
    return existing


def check_freshness(ranked: list[tuple[int, float, dict]], meta: dict) -> list[str]:
    """Verify every generated artifact matches what generate.py would emit."""
    drift: list[str] = []
    expected_json = render_registry_json(ranked, meta)
    if not REGISTRY_JSON.exists() or REGISTRY_JSON.read_text(encoding="utf-8") != expected_json:
        drift.append("data/problems.json is out of date")

    expected_ranking = render_ranking_md(ranked, meta)
    if not RANKING_MD.exists() or RANKING_MD.read_text(encoding="utf-8") != expected_ranking:
        drift.append("RANKING.md is out of date")

    if README.exists():
        cur_readme = README.read_text(encoding="utf-8")
        if render_patched_readme(cur_readme, ranked) != cur_readme:
            drift.append("README.md ranking block is out of date")

    for rank, css, p in ranked:
        folder = PROBLEMS_DIR / p["slug"]
        templates = dossier_templates(p, rank, css)
        meta_path = folder / "metadata.json"
        if not meta_path.exists() or meta_path.read_text(encoding="utf-8") != templates["metadata.json"]:
            drift.append(f"problems/{p['slug']}/metadata.json is out of date")
        readme_path = folder / "README.md"
        if readme_path.exists():
            cur = readme_path.read_text(encoding="utf-8")
            if refresh_dossier_readme_text(cur, p, rank, css) != cur:
                drift.append(f"problems/{p['slug']}/README.md rank/status header is out of date")
    return drift


TEMPLATE_MARKER = "<!-- DOSSIER:"


def _is_unauthored(folder: Path) -> bool:
    """A folder is 'unauthored' if every section file still holds its template
    marker (or no section files exist). Such folders are safe to remove."""
    section_files = list(folder.glob("*.md"))
    if not section_files:
        return True
    for md in section_files:
        if md.name == "README.md":
            continue
        if TEMPLATE_MARKER not in md.read_text(encoding="utf-8"):
            return False
    return True


def reconcile(desired_slugs: set[str]) -> tuple[int, list[str]]:
    """Remove orphan folders (slug no longer in registry) that are unauthored;
    warn about authored orphans so human work is never silently deleted."""
    import shutil

    removed = 0
    warnings: list[str] = []
    if not PROBLEMS_DIR.exists():
        return 0, warnings
    for folder in PROBLEMS_DIR.iterdir():
        if not folder.is_dir() or folder.name in desired_slugs:
            continue
        if _is_unauthored(folder):
            shutil.rmtree(folder)
            removed += 1
        else:
            warnings.append(
                f"orphan folder '{folder.name}' has authored content but no registry "
                f"entry — left in place; rename its slug or remove manually."
            )
    return removed, warnings


def scaffold(ranked: list[tuple[int, float, dict]]) -> tuple[int, int]:
    created = 0
    refreshed_headers = 0
    for rank, css, p in ranked:
        folder = PROBLEMS_DIR / p["slug"]
        for rel, content in dossier_templates(p, rank, css).items():
            path = folder / rel
            if path.exists():
                if rel == "metadata.json":
                    path.write_text(content, encoding="utf-8", newline="\n")
                elif rel == "README.md":
                    cur = path.read_text(encoding="utf-8")
                    updated = refresh_dossier_readme_text(cur, p, rank, css)
                    if updated != cur:
                        path.write_text(updated, encoding="utf-8", newline="\n")
                        refreshed_headers += 1
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            created += 1
    return created, refreshed_headers


# --------------------------------------------------------------------------- #
#  Main
# --------------------------------------------------------------------------- #
def main() -> int:
    ap = argparse.ArgumentParser(description="Build the Unsolved Mathematics Atlas.")
    ap.add_argument("--check", action="store_true", help="validate + verify generated views have zero drift")
    args = ap.parse_args()

    data = yaml.safe_load(REGISTRY_YAML.read_text(encoding="utf-8"))
    meta = data["meta"]
    problems = data["problems"]

    errors = validate(problems)
    hard_errors = [e for e in errors if not e.startswith("WARN")]
    for e in errors:
        print(("  " if e.startswith("WARN") else "ERROR: ") + e, file=sys.stderr)
    if hard_errors:
        return 1

    ranked = rank_problems(problems)

    if args.check:
        drift = check_freshness(ranked, meta)
        if drift:
            print("ERROR: Generated views are stale. Run 'python scripts/generate.py':", file=sys.stderr)
            for item in drift[:25]:
                print(f"  - {item}", file=sys.stderr)
            if len(drift) > 25:
                print(f"  ... and {len(drift) - 25} more", file=sys.stderr)
            return 1
        print(f"OK: {len(problems)} problems validated; all generated views are current.")
        return 0

    REGISTRY_JSON.write_text(render_registry_json(ranked, meta), encoding="utf-8", newline="\n")
    RANKING_MD.write_text(render_ranking_md(ranked, meta), encoding="utf-8", newline="\n")
    desired = {p["slug"] for _, _, p in ranked}
    removed, warnings = reconcile(desired)
    for w in warnings:
        print("  WARN: " + w, file=sys.stderr)
    created, refreshed = scaffold(ranked)
    if README.exists():
        cur_readme = README.read_text(encoding="utf-8")
        README.write_text(render_patched_readme(cur_readme, ranked), encoding="utf-8", newline="\n")

    if removed:
        print(f"Reconciled: removed {removed} orphan folder(s).")
    print(
        f"Built {len(ranked)} problems · scaffolded {created} new files · "
        f"refreshed {refreshed} dossier README headers."
    )
    print(f"  -> {REGISTRY_JSON.relative_to(ROOT)}")
    print(f"  -> {RANKING_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
